import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const root = new URL("../", import.meta.url);
const read = (path) => readFile(new URL(path, root), "utf8");
const metadata = async (name) => JSON.parse(await read(`node_modules/${name}/package.json`));
const next = await metadata("next");

// Reviewed against Next's production bundle analysis. An updated Next version
// needs a new inventory review, including its separately copied legacy polyfill.
if (next.version !== "16.4.5") {
  throw new Error("Review the browser license inventory for this Next.js version before updating the version guard.");
}

const packages = [
  ["next", "license.md"],
  ["react", "LICENSE"],
  ["react-dom", "LICENSE"],
  ["scheduler", "LICENSE"],
  ["@swc/helpers", "LICENSE"],
];
const bundled = [
  "react", "react-dom", "scheduler", "react-server-dom-turbopack",
  "react-server-dom-webpack", "process", "path-to-regexp",
];
const sections = [];
for (const [name, licenseFile] of packages) {
  const pkg = await metadata(name);
  const path = `node_modules/${name}/${licenseFile}`;
  sections.push(`${name} ${pkg.version} (${pkg.license})\nSource: ${path}\n\n${(await read(path)).trim()}`);
}
for (const name of bundled) {
  const path = `node_modules/next/dist/compiled/${name}/LICENSE`;
  sections.push(`${name} (bundled with Next.js ${next.version})\nSource: ${path}\n\n${(await read(path)).trim()}`);
}

// Next ships this minified dependency without a separate license file. Preserve
// its version-specific upstream notice here, and fail if the bundled version
// changes instead of silently applying an old copyright notice to a new build.
const polyfill = await read("node_modules/next/dist/build/polyfills/polyfill-nomodule.js");
if (!polyfill.includes('version:"3.38.1"') || !polyfill.includes("2014-2024 Denis Pushkarev")) {
  throw new Error("Review the core-js version and refresh its bundled license notice.");
}
sections.push(`core-js 3.38.1 (MIT; Next.js legacy-browser polyfill)\nSource: https://github.com/zloirock/core-js/blob/v3.38.1/LICENSE\n\n${(await read("licenses/core-js-3.38.1-LICENSE")).trim()}`);

const header = `Kaan Gallery — third-party browser software notices

Generated by scripts/generate-license-notices.mjs from installed dependencies.
This file includes the browser framework, bundled helpers, fallback runtimes,
and legacy-browser polyfill; not every component runs on every page/browser.
Backend dependencies such as Psycopg and Sharp/libvips are not browser code.

The following notices apply to the named third-party components only.
They do not grant rights to Kaan Gallery's original code, artwork, photographs,
or branding, which remain subject to the repository's LICENSE notice.
`;
const output = `${header}\n${sections.join(`\n\n${"=".repeat(78)}\n\n`)}\n`;
const destination = new URL("public/THIRD_PARTY_LICENSES.txt", root);
if (process.argv.includes("--check")) {
  if (await readFile(destination, "utf8") !== output) {
    throw new Error("THIRD_PARTY_LICENSES.txt is stale. Run npm run licenses:generate and commit the result.");
  }
  console.log("Third-party notices match the installed dependency licenses.");
} else {
  await writeFile(destination, output);
  console.log(`Generated ${fileURLToPath(destination)} (${sections.length} components).`);
}
